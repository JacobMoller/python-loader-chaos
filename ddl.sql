--
-- Name: check_matching_tagtype(); Type: FUNCTION; Schema: public; Owner: bjorn
--

CREATE FUNCTION public.check_matching_tagtype() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF (NEW.tagtype_id IS DISTINCT FROM (SELECT tagtype_id FROM public.tagsets WHERE id = NEW.tagset_id)) THEN
        RAISE EXCEPTION 'Tagtype_id does not match the corresponding tagset''s tagtype_id';
    END IF;
    RETURN NEW;
END;
$$;


ALTER FUNCTION public.check_matching_tagtype() OWNER TO postgres;

--
-- Name: check_nodes_tagset(); Type: FUNCTION; Schema: public; Owner: bjorn
--

CREATE FUNCTION public.check_nodes_tagset() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
  tagset_id_for_hierarchy INTEGER;
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM public.tags t 
    JOIN (SELECT tagset_id FROM public.hierarchies WHERE id = NEW.hierarchy_id) h
    ON t.tagset_id = h.tagset_id
    WHERE t.id = NEW.tag_id
  ) THEN
    RAISE EXCEPTION 'The tag_id does not belong to the correct tagset_id for this hierarchy.';
  END IF;
  RETURN NEW;
END;
$$;


ALTER FUNCTION public.check_nodes_tagset() OWNER TO postgres;

