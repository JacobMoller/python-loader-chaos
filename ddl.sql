--
-- Name: get_level_from_parent_node(integer, integer); Type: FUNCTION; Schema: public; Owner: bjorn
--

CREATE FUNCTION public.get_level_from_parent_node(integer, integer) RETURNS SETOF public.nodes
    LANGUAGE sql
    AS $_$
    select N.id, N.tag_id, N.hierarchy_id, N.parentnode_id
	from public.nodes N 
	where N.parentnode_id = $1 and N.hierarchy_id = $2
$_$;


ALTER FUNCTION public.get_level_from_parent_node(integer, integer) OWNER TO postgres;

--
-- Name: get_level_from_sibling(integer, integer); Type: FUNCTION; Schema: public; Owner: bjorn
--

CREATE FUNCTION public.get_level_from_sibling(integer, integer) RETURNS SETOF public.nodes
    LANGUAGE sql
    AS $_$
    select N.id, N.tag_id, N.hierarchy_id, N.parentnode_id
	from public.nodes N 
		join public.nodes N1 on N.parentnode_id = N1.parentnode_id
	where N1.id = $1 and N1.hierarchy_id = $2
$_$;


ALTER FUNCTION public.get_level_from_sibling(integer, integer) OWNER TO postgres;

--
-- Name: get_subtree_from_parent_node(integer); Type: FUNCTION; Schema: public; Owner: bjorn
--

CREATE FUNCTION public.get_subtree_from_parent_node(integer) RETURNS SETOF public.nodes
    LANGUAGE sql
    AS $_$
WITH RECURSIVE allsubtags AS(
    select N.id, N.tag_id, N.hierarchy_id, N.parentnode_id
	from public.nodes N 
	where N.id = $1
    UNION ALL
    select N.id, N.tag_id, N.hierarchy_id, N.parentnode_id
	from public.nodes N
		join allsubtags A on A.id = N.parentnode_id
)  select * from allsubtags
$_$;


ALTER FUNCTION public.get_subtree_from_parent_node(integer) OWNER TO postgres;

