--
-- Name: nodes_taggings; Type:  VIEW; Schema: public; Owner: bjorn
--

CREATE VIEW public.nodes_taggings AS
 SELECT h.parentnode_id,
    h.id AS node_id,
    h.tag_id,
    r.object_id
   FROM (( SELECT n.parentnode_id,
            n.id,
            (public.get_subtree_from_parent_node(n.id)).tag_id AS tag_id
           FROM public.nodes n) h
     JOIN public.taggings r ON ((r.tag_id = h.tag_id)))
  ;


ALTER TABLE public.nodes_taggings OWNER TO postgres;

